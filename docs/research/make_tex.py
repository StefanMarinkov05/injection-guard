#!/usr/bin/env python3
"""Turn the public result files (data/*.json) into LaTeX: generated/values.tex (one macro per number, used in the text
as \\val{<id>.<field>}) and generated/*.tex tables and plot coordinates. No number in the paper or the methods document
is typed by hand.

    python3 -I docs/research/make_tex.py
"""
import json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
GEN = os.path.join(HERE, "generated")


def fp(p):
    """p-values: 2 significant digits, scientific below 0.001, '<0.0001' for permutation floors."""
    if p is None:
        return "-"
    if p >= 0.9995:
        return "1"
    if p < 0.001:
        m, e = f"{p:.1e}".split("e")
        return f"{m}\\times 10^{{{int(e)}}}"
    return f"{p:.3f}".rstrip("0").rstrip(".") if p >= 0.01 else f"{p:.4f}".rstrip("0")


def pct(x, d=1):
    return "-" if x is None else f"{100 * x:.{d}f}\\%"


def esc(s):
    return str(s).replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace("#", "\\#")


def fmt(field, v):
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float) and (field in ("p", "p_holm", "fisher_p", "strat_p", "max_p") or field.startswith("p_at_")):
        return fp(v)
    if isinstance(v, float) and (field in ("rate", "rate1", "rate2", "lo", "hi", "rd", "top_share", "lower95_one_sided", "cp_lo", "cp_hi",
                                           "rule_of_three_upper", "mean", "min", "max", "min_rd", "mde_from_2pct", "mde_from_base5", "base5", "power_4x_vs_5x_observed", "p0")):
        return pct(v)
    if isinstance(v, float):
        return "\\infty" if math.isinf(v) else (f"{v:.2f}" if abs(v) < 100 else f"{v:.0f}")
    if isinstance(v, list) and len(v) == 2 and all(isinstance(x, float) for x in v):
        return f"[{pct(v[0])}, {pct(v[1])}]" if not field.startswith("kappa") else f"[{v[0]:.2f}, {v[1]:.2f}]"
    return esc(v)


def flatten(prefix, obj, out):
    if isinstance(obj, dict):
        for k, v in obj.items():
            flatten(f"{prefix}.{k}" if prefix else k, v, out)
    elif isinstance(obj, list) and obj and isinstance(obj[0], dict) and "id" in obj[0]:
        for t in obj:
            for k, v in t.items():
                if k != "id":
                    flatten(f"{t['id']}.{k}", v, out)
    elif isinstance(obj, list) and len(obj) == 1 and isinstance(obj[0], dict):
        flatten(prefix.removesuffix(".rows"), obj[0], out)
    elif isinstance(obj, list) and obj and isinstance(obj[0], dict) and any(k in obj[0] for k in ("model", "harm", "area", "verdict")):
        lab = next(k for k in ("model", "harm", "area", "verdict") if k in obj[0])
        for t in obj:
            flatten(f"{prefix.removesuffix('.rows')}.{t[lab]}", {k: v for k, v in t.items() if k != lab}, out)
    else:
        out[prefix] = fmt(prefix.rsplit(".", 1)[-1], obj)


def main():
    os.makedirs(GEN, exist_ok=True)
    vals = {}
    for name in sorted(os.listdir(DATA)):
        if name.endswith(".json"):
            obj = json.load(open(os.path.join(DATA, name)))
            if name == "stats.json":
                for fam, tests in obj.pop("families").items():
                    flatten("", tests, vals)
            flatten("" if name == "stats.json" else name[:-5], obj, vals)
    tr = os.path.join(HERE, "..", "test_results.json")  # the plugin's own test run (docs/gen_docs.py)
    if os.path.exists(tr):
        t = json.load(open(tr))
        vals["tests_total"], vals["tests_failures"], vals["plugin_version"] = str(t["total"]), str(t["failures"] + t["errors"]), esc(t["version"])
    with open(os.path.join(GEN, "values.tex"), "w") as f:
        f.write("% generated by make_tex.py from data/*.json - do not edit\n")
        f.write("\\makeatletter\n\\newcommand{\\val}[1]{\\ifcsname igv@#1\\endcsname\\csname igv@#1\\endcsname\\else\\textcolor{harm}{\\textbf{??\\detokenize{#1}}}\\fi}\n")
        for k, v in sorted(vals.items()):
            f.write(f"\\expandafter\\def\\csname igv@{k}\\endcsname{{\\ensuremath{{{v}}}}}\n" if any(c in v for c in "\\^") else
                    f"\\expandafter\\def\\csname igv@{k}\\endcsname{{{v}}}\n")
        f.write("\\makeatother\n")
    print(f"values.tex: {len(vals)} values")
    tables()


def tables():
    st = json.load(open(os.path.join(DATA, "stats.json")))
    F = st["families"]
    RV = st.get("review", {})
    # the test table (one line per hypothesis family member that the paper reports)
    rows = []
    for t in F["F1"]:
        rows.append(("F1", f"{esc(t['model'])}: $p\\le{st['p0'] * 100:.0f}\\%$", "exact binomial (one-sided)",
                     f"{t['k']}/{t['n']}", fp(t["p_holm"])))
    for t in F["F2"] + F["F3"]:
        rows.append((t["id"][:2], f"{esc(t['groups'][0])} = {esc(t['groups'][1])}" + (" (w/o bootstrap)" if "without" in t["id"] else ""),
                     "exact stratified (scenario)", f"{t['k1']}/{t['n1']} vs {t['k2']}/{t['n2']}", fp(t["p_holm"])))
    for t in F["F4"]:
        rows.append(("F4", f"{esc(t['model'])}: no effort trend", "Cochran-Armitage", " ".join(t["by_effort"].values()), fp(t["p_holm"])))
    for t in F["F5"]:
        rows.append(("F5", f"{esc(t['model'])}: prompt has no effect", "exact McNemar", f"{t['vanilla_k']} vs {t['defended_k']} of {t['pairs']}", fp(t["p_holm"])))
    for t in F["F6"]:
        rows.append(("F6", f"{t['generation']}: covered = missed", "Fisher exact", f"{t['k_covered']}/{t['n_covered']} vs {t['k_missed']}/{t['n_missed']}", fp(t["p_holm"])))
    t = F["F7"][0]
    rows.append(("F7", "rule judge = LLM judge", "exact McNemar", f"{t['rule_yes']} vs {t['llm_yes']} of {t['runs_both']}", fp(t["p_holm"])))
    for t in F["F8"]:
        rows.append(("F8", f"{esc(t['group'])}: one rate for all scenarios", "permutation $X^2$", f"{t['k']}/{t['n']}", fp(t["p_holm"])))
    if "F9" in F:
        t = F["F9"][0]
        rows.append(("F9", "5.0 = 5.5 on bootstrap", "Fisher exact", f"{t['k_5_0']}/{t['n_5_0']} vs {t['k_5_5']}/{t['n_5_5']}", fp(t["p_holm"])))
    if "F10" in F:
        a, b = F["F10"]
        rows.append(("F10", "agents: 5.0 = 5.5 on bootstrap", "Fisher exact", f"{a['k_5_0']}/{a['n_5_0']} vs {a['k_5_5']}/{a['n_5_5']}", fp(a["p_holm"])))
        rows.append(("F10", "5.5: agent = single call on bootstrap", "Fisher exact", f"{b['k_agent']}/{b['n_agent']} vs {b['k_single']}/{b['n_single']}", fp(b["p_holm"])))
    with open(os.path.join(GEN, "tests-table.tex"), "w") as f:
        f.write("% generated by make_tex.py\n\\begin{longtable}{@{}lP{4.3cm}P{2.9cm}P{2.6cm}r@{}}\n\\toprule\n"
                "Fam. & $H_0$ & Test & Data & $p_{\\text{Holm}}$\\\\\n\\midrule\\endhead\n")
        last = None
        for fam, h0, test, data, p in rows:
            if last and fam != last:
                f.write("\\addlinespace[2pt]\n")
            f.write(f"{fam if fam != last else ''} & {h0} & {test} & {data} & ${p}$\\\\\n")
            last = fam
        f.write("\\bottomrule\n\\end{longtable}\n")
    with open(os.path.join(GEN, "f1-table.tex"), "w") as f:
        f.write("% generated by make_tex.py\n\\begin{tabular}{@{}lrrrrrrr@{}}\\toprule\n"
                "Model & $k/n$ & rate & CP 95\\% & $p$ ($p_0{=}1\\%$) & $p_{\\text{Holm}}$ & $p$ ($p_0{=}5\\%$) & \\shortstack{inj.\\\\$k/n$}\\\\\\midrule\n")
        INJ = {t["model"]: t for t in RV.get("F1_injection", [])}
        for t in F["F1"]:
            if t["id"] == "F1-all-runs":
                f.write("\\midrule\n")
            f.write(f"{esc(t['model'])} & {t['k']}/{t['n']} & {pct(t['rate'])} & [{pct(t['cp_lo'])}, {pct(t['cp_hi'])}] & "
                    f"${fp(t['p'])}$ & ${fp(t['p_holm'])}$ & ${fp(t['p_at_p0_5pct'])}$ & "
                    + (f"{INJ[t['model']]['k']}/{INJ[t['model']]['n']}" if t['model'] in INJ else "-") + "\\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    # per-model plot coordinates: rate with Clopper-Pearson interval
    with open(os.path.join(GEN, "models-plot.tex"), "w") as f:
        f.write("% generated by make_tex.py\n\\addplot+[harm, fill=harm!55, draw=harm, error bars/.cd, x dir=both, x explicit, error bar style={mute}]\n"
                "coordinates {\n")
        for t in F["F1"][:-1]:
            r = 100 * t["rate"]
            f.write(f"  ({r:.2f},{{{esc(t['model'])}}}) -= ({r - 100 * t['cp_lo']:.2f},0) += ({100 * t['cp_hi'] - r:.2f},0)\n")
        f.write("};\n")
    with open(os.path.join(GEN, "models-labels.tex"), "w") as f:
        f.write("\\def\\igModelLabels{" + ",".join("{" + esc(t["model"]) + "}" for t in F["F1"][:-1]) + "}\n")
    ab = os.path.join(DATA, "guard_ab.json")
    if os.path.exists(ab):
        A = json.load(open(ab))
        with open(os.path.join(GEN, "ab-table.tex"), "w") as f:
            f.write("% generated by make_tex.py\n\\begin{tabular}{@{}lrrrrrr@{}}\\toprule\n"
                    "Model & pairs & \\shortstack{followed\\\\off} & \\shortstack{followed\\\\on} & \\shortstack{off only /\\\\on only} & McNemar $p$ & \\shortstack{reported\\\\off / on}\\\\\\midrule\n")
            for t in A["per_model"]:
                f.write(f"{esc(t['model'])} & {t['pairs']} & {t['off_followed']} & {t['on_followed']} & {t['off_only']} / {t['on_only']} & "
                        f"${fp(t['p'])}$ & {t['off_reported']} / {t['on_reported']}\\\\\n")
            f.write("\\bottomrule\n\\end{tabular}\n")
        with open(os.path.join(GEN, "ab-cases.tex"), "w") as f:
            f.write("% generated by make_tex.py\n\\begin{tabular}{@{}llllll@{}}\\toprule\n"
                    "Case & Model & Static scan & Off & On & Guard-on outcome\\\\\\midrule\n")
            for r in A["pairs"]:
                if r["off_followed"] or r["on_followed"] or r["guard_gate"]:
                    yn = lambda x: "followed" if x else "resisted"  # noqa: E731
                    f.write(f"{r['case']} & {esc(r['model'])} & {r['static_guard']} & {yn(r['off_followed'])} & {yn(r['on_followed'])} & {esc(r['outcome'])}\\\\\n")
            f.write("\\bottomrule\n\\end{tabular}\n")
    def kn(k, n):
        return f"{k}/{n} ({100 * k / n:.1f}\\%)" if n else "-"
    for name, col, label in (("harms", "harm", "Harm class"), ("sectors", "area", "Use case")):
        rows_ = json.load(open(os.path.join(DATA, name + ".json")))["rows"]
        with open(os.path.join(GEN, f"{name}-table.tex"), "w") as f:
            f.write("% generated by make_tex.py\n\\begin{tabularx}{\\linewidth}{@{}P{2.6cm}rrrrL@{}}\\toprule\n"
                    f"{label} & cases & scan covers & 4.x followed & 5.x followed & followed cases\\\\\\midrule\n")
            for r in sorted(rows_, key=lambda r: -(r["k4"] + r["k5"])):
                fl = sorted(set((r["failing_4x"] + ", " + r["failing_5x"]).replace("none", "").replace(" ", "").split(",")) - {""})
                f.write(f"{esc(r[col])} & {r['scenarios']} & {r['guard_covers']} & {kn(r['k4'], r['n4'])} & {kn(r['k5'], r['n5'])} & {', '.join(fl) or 'none'}\\\\\n")
            f.write("\\bottomrule\n\\end{tabularx}\n")

    # tables added after the external review: run accounting, construct split, strata of the generation test
    acc = RV["accounting"]
    with open(os.path.join(GEN, "accounting-table.tex"), "w") as f:
        f.write("% generated by make_tex.py\n\\begin{tabular}{@{}lrrrrr@{}}\\toprule\n"
                "Model & default & efforts low-max & security prompt & pooled & C38 follow-up\\\\\\midrule\n")
        for m, a in acc["per_model"].items():
            f.write(f"{esc(m)} & {a['default']} & {a['efforts_low_to_max'] or ''} & {a['security_prompt'] or ''} & {a['pooled']} & {a['followup_c38'] or ''}\\\\\n")
        f.write(f"\\midrule all & {acc['default_runs']} & {sum(a['efforts_low_to_max'] for a in acc['per_model'].values())} & "
                f"{sum(a['security_prompt'] for a in acc['per_model'].values())} & {acc['pooled_runs']} & {acc['followup_runs']}\\\\\n"
                "\\bottomrule\n\\end{tabular}\n")
    def kn_(t):
        k, n = map(int, t.split("/"))
        return f"{k}/{n} ({100 * k / n:.1f}\\%)" if n else "-"
    with open(os.path.join(GEN, "construct-table.tex"), "w") as f:
        d4 = [t for t in F["F2"] if t["id"] == "F2-generation-without-bootstrap"][0]
        f.write("% generated by make_tex.py\n\\begin{tabular}{@{}lll@{}}\\toprule\n"
                "Outcome and run universe & 4.x (6 models) & 5.x (5 models)\\\\\\midrule\n"
                f"Injection (42 cases), default effort & {kn_(str(d4['k1']) + '/' + str(d4['n1']))} & {kn_(str(d4['k2']) + '/' + str(d4['n2']))}\\\\\n"
                f"Injection (42 cases), all pooled runs & {kn_(RV['pooled_4x']['injection'])} & {kn_(RV['pooled_5x']['injection'])}\\\\\n"
                f"Process step C38, default effort & {kn_(RV['process_c38_default']['4.x'])} & {kn_(RV['process_c38_default']['5.x'])}\\\\\n"
                f"Process step C38, all pooled runs & {kn_(RV['pooled_4x']['process'])} & {kn_(RV['pooled_5x']['process'])}\\\\\n"
                f"Both (43 cases), default effort & {kn_(RV['pooled_4x']['all'])} & {kn_(str(F['F2'][0]['k2']) + '/' + str(F['F2'][0]['n2']))}\\\\\n"
                f"Both (43 cases), all pooled runs & {kn_(RV['pooled_4x']['all'])} & {kn_(RV['pooled_5x']['all'])}\\\\\n"
                "\\bottomrule\n\\end{tabular}\n")
    loo = {t["dropped"]: t for t in RV["F2_leave_one_out"]["rows"]}
    with open(os.path.join(GEN, "strata-table.tex"), "w") as f:
        f.write("% generated by make_tex.py\n\\begin{tabular}{@{}lrrr@{}}\\toprule\n"
                "Scenario & 4.x follows & 5.x follows & stratified $p$ without it\\\\\\midrule\n")
        for t in sorted(RV["F2_strata_with_events"], key=lambda t: t["scenario"]):
            f.write(f"{t['scenario']} & {t['k4']}/{t['n4']} & {t['k5']}/{t['n5']} & ${fp(loo[t['scenario']]['strat_p'])}$\\\\\n")
        f.write(f"\\midrule other {43 - len(RV['F2_strata_with_events'])} scenarios & 0 & 0 & \\\\\n\\bottomrule\n\\end{{tabular}}\n")
    # where a guard is needed: a fixed decision rule over every pooled run (added after the external review)
    import importlib.util
    spec = importlib.util.spec_from_file_location("recompute", os.path.join(HERE, "recompute.py"))
    rc = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(rc)
    runs = [r for r in json.load(open(os.path.join(DATA, "runs.json")))["rows"] if r["pooled"]]
    CS = {c["case"]: c for c in json.load(open(os.path.join(DATA, "cases.json")))["rows"]}
    order = ["browsing", "coding", "documents", "scanning", "shopping", "tasks", "process"]
    cell = {}
    for r in runs:
        u = "process" if r["case"] == "C38" else CS[r["case"]]["use_case"]
        c = cell.setdefault((u, rc.gen(r["model"])), [0, 0])
        c[0] += r["followed"]
        c[1] += 1

    def verdict(k, n):
        lo, hi = rc.clopper_pearson(k, n)
        tag = "\\textbf{needed}" if lo > 0.01 else ("seen" if k else "none")
        return f"{k}/{n} [{100 * lo:.1f}, {100 * hi:.1f}] {tag}"
    with open(os.path.join(GEN, "need-table.tex"), "w") as f:
        f.write("% generated by make_tex.py\n\\begin{tabular}{@{}llll@{}}\\toprule\n"
                "Use case (cases) & 4.x: follows [95\\% CI] & 5.x: follows [95\\% CI] & scanner sees\\\\\\midrule\n")
        for u in order:
            cs = sorted({c for c in CS if (c == "C38") == (u == "process") and (u == "process" or CS[c]["use_case"] == u)})
            cov = sum(CS[c]["static_guard"] == "covers" for c in cs)
            name = "process step (C38)" if u == "process" else f"{u} ({len(cs)})" + (", without C38" if u == "tasks" else "")
            f.write(f"{name} & {verdict(*cell[(u, 4)])} & {verdict(*cell[(u, 5)])} & {cov} of {len(cs)}\\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    cases = json.load(open(os.path.join(DATA, "cases.json")))["rows"]
    with open(os.path.join(GEN, "catalogue.tex"), "w") as f:
        f.write("% generated by make_tex.py\n\\begin{longtable}{@{}lP{2.7cm}P{2.1cm}P{5.3cm}r@{}}\\toprule\n"
                "Case & Use case / harm & Technique & What the agent did when it followed & Runs\\\\\\midrule\\endhead\n")
        for c in sorted((c for c in cases if c["follows"]), key=lambda c: (-c["follows"], c["case"])):
            f.write(f"{c['case']} & {esc(c['use_case'])}; {esc(c['harm'])} & {esc(c['technique_class'])}"
                    f"{' (scan misses)' if c['static_guard'] == 'misses' else ''} & {esc(c['behavior_when_followed'])} & {c['follows']}/{c['runs']}\\\\\n")
        f.write("\\bottomrule\n\\end{longtable}\n")
    print("tables: tests-table.tex, models-plot.tex, f1-table.tex, ab-table.tex, ab-cases.tex")


if __name__ == "__main__":
    main()
